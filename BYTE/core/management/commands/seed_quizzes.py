class Command(BaseCommand):
    help = 'Добавляет три стартовых теста; существующие тесты не изменяет.'

    def add_arguments(self, parser):
        parser.add_argument('--publish', action='store_true', help='Сразу опубликовать только новые тесты.')

    @transaction.atomic
    def handle(self, *args, **options):
        created = 0
        for slug, title, rows in QUIZZES:
            if Quiz.objects.filter(title=title).exists():
                continue
            quiz = Quiz.objects.create(title=title, section=Section.objects.filter(slug=slug).first(), description='Пять вопросов, чтобы закрепить основные понятия. После завершения — разбор ответов.', is_published=options['publish'])
            for index, (text, answers, correct, explanation) in enumerate(rows):
                Question.objects.create(quiz=quiz, text=text, option_a=answers[0], option_b=answers[1], option_c=answers[2], option_d=answers[3], correct=correct, explanation=explanation, order=index)
            created += 1
        self.stdout.write(self.style.SUCCESS(f'Добавлено тестов: {created}.'))
