class Command(BaseCommand):
    help = "Создаёт 16 тем ЕНТ с подразделами. Уже существующие разделы не перезаписывает."

    def handle(self, *args, **options):
        created_topics = created_subs = 0

        for topic_index, (slug, title, summary, subs) in enumerate(TOPICS, start=1):
            topic, was_created = Section.objects.get_or_create(
                slug=slug,
                defaults={
                    "title": title,
                    "summary": summary,
                    "order": topic_index * 10,
                    "content": SAMPLE_CONTENT.get(slug, ""),
                },
            )
            created_topics += was_created

            for sub_index, (sub_slug, sub_title) in enumerate(subs, start=1):
                _, sub_created = Section.objects.get_or_create(
                    slug=sub_slug,
                    defaults={
                        "title": sub_title,
                        "parent": topic,
                        "order": sub_index * 10,
                        "content": SAMPLE_CONTENT.get(sub_slug, ""),
                    },
                )
                created_subs += sub_created

        self.stdout.write(self.style.SUCCESS(
            f"Готово: создано тем — {created_topics}, подразделов — {created_subs}."
        ))
        self.stdout.write("Тексты добавляйте в админке: /admin/ → Материалы. "
                          "Готовые примеры оформления есть в разделах «Перевод между системами счисления», "
                          "«Единицы измерения информации», «Логические операции», «Циклы».")
